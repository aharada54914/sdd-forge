#!/usr/bin/env python3
"""Copy the shared diagnostics mechanism into independently built MCP packages."""
import argparse
from pathlib import Path

PACKAGES = ('local-env-mcp', 'ci-mcp')
HEADER = '// Generated by mcp/shared/sync-diagnostics.py; edit mcp/shared/diagnostics-core.ts.\n'


def synchronize(root: Path, *, check: bool) -> list[str]:
    """Return stale paths; check mode never writes, update mode copies exact UTF-8 bytes."""
    expected = HEADER.encode('utf-8') + (root / 'mcp/shared/diagnostics-core.ts').read_bytes()
    stale = []
    for package in PACKAGES:
        target = root / f'mcp/{package}/src/diagnostics-core.ts'
        if not target.is_file() or target.read_bytes() != expected:
            stale.append(target.relative_to(root).as_posix())
            if not check:
                target.write_bytes(expected)
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='report stale copies without changing them')
    args = parser.parse_args()
    stale = synchronize(Path(__file__).resolve().parents[2], check=args.check)
    for path in stale:
        print(f'{"stale" if args.check else "updated"}: {path}')
    return int(args.check and bool(stale))


if __name__ == '__main__':
    raise SystemExit(main())
