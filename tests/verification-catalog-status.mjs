#!/usr/bin/env node
/**
 * Compares tests/verification-catalog.json with what .github/workflows/test.yml
 * actually runs (#862). The catalog is a v1 asset: its `ci_jobs` names mostly
 * no longer exist, so a catalog link never counts as "run in CI". A suite is
 * "run" only when a current job's steps name its path.
 *
 * Usage:
 *   node tests/verification-catalog-status.mjs           # print the report
 *   node tests/verification-catalog-status.mjs --write   # update docs/operations/verification-catalog-status.md
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const REPORT_PATH = 'docs/operations/verification-catalog-status.md';

// Job id -> the job's text, from the top-level `jobs:` mapping (2-space keys).
export function parseWorkflowJobs(workflowText) {
  const lines = workflowText.split('\n');
  const start = lines.findIndex((l) => /^jobs:\s*$/.test(l));
  const jobs = new Map();
  let current = null;
  for (const line of start === -1 ? [] : lines.slice(start + 1)) {
    if (/^\S/.test(line)) break;
    const key = /^ {2}([A-Za-z0-9_-]+):\s*$/.exec(line);
    if (key) {
      current = key[1];
      jobs.set(current, '');
    } else if (current) {
      jobs.set(current, `${jobs.get(current)}${line}\n`);
    }
  }
  return jobs;
}

export function classifyCatalog(root = REPO_ROOT) {
  const catalog = JSON.parse(fs.readFileSync(path.join(root, 'tests/verification-catalog.json'), 'utf8'));
  const jobs = parseWorkflowJobs(fs.readFileSync(path.join(root, '.github/workflows/test.yml'), 'utf8'));
  const suites = catalog.suites.map((suite) => {
    const runIn = [...jobs].filter(([, text]) => text.includes(suite.path)).map(([id]) => id);
    let state = 'not-in-ci';
    if (!fs.existsSync(path.join(root, suite.path))) state = 'file-missing';
    else if (runIn.length > 0) state = 'run';
    return { path: suite.path, catalogJobs: suite.ci_jobs || [], runIn, state };
  });
  const catalogJobNames = [...new Set(suites.flatMap((s) => s.catalogJobs))].sort();
  return { jobs: [...jobs.keys()], catalogJobNames, suites };
}

const STATE_LABEL = { run: '実行中', 'not-in-ci': 'CI 外（ファイルあり・現行ジョブは実行しない）', 'file-missing': '廃止（ファイルなし）' };

export function renderReport({ jobs, catalogJobNames, suites }) {
  const out = [
    '# Verification catalog status',
    '',
    '<!-- Generated by `node tests/verification-catalog-status.mjs --write`. Do not edit by hand. -->',
    '',
    '`tests/verification-catalog.json` は v1 の CI 構成の資産です。`ci_jobs` に書かれたジョブ名は現行の',
    '`.github/workflows/test.yml` にほとんど存在しません。カタログのリンクだけでは「CI で実行済み」と数えず、',
    '現行ジョブの手順がそのパスを実行している場合だけ「実行中」とします（#862）。',
    '',
    `現行ジョブ: ${jobs.map((j) => `\`${j}\``).join(', ')}`,
    '',
    '## カタログのジョブ名と現行ジョブ',
    '',
    '| カタログのジョブ名 | 現行に存在 | 登録数 | 実行中 | CI 外 | 廃止 |',
    '|---|---|---|---|---|---|',
  ];
  for (const name of catalogJobNames) {
    const listed = suites.filter((s) => s.catalogJobs.includes(name));
    const count = (state) => listed.filter((s) => s.state === state).length;
    out.push(`| \`${name}\` | ${jobs.includes(name) ? 'yes' : 'no'} | ${listed.length} | ${count('run')} | ${count('not-in-ci')} | ${count('file-missing')} |`);
  }
  out.push('', '## `posix-regression` に登録されたスイート', '', '| スイート | 状態 | 実行している現行ジョブ |', '|---|---|---|');
  for (const s of suites.filter((x) => x.catalogJobs.includes('posix-regression'))) {
    out.push(`| \`${s.path}\` | ${STATE_LABEL[s.state]} | ${s.runIn.map((j) => `\`${j}\``).join(', ') || '—'} |`);
  }
  out.push('');
  return out.join('\n');
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const report = renderReport(classifyCatalog());
  if (process.argv.includes('--write')) {
    fs.writeFileSync(path.join(REPO_ROOT, REPORT_PATH), report, 'utf8');
  } else {
    process.stdout.write(report);
  }
}
