#!/usr/bin/env python3
"""Render the model routing tables from the registry and policy (single source of truth).

The tier mapping, role floors and historical-model tables in the routing
documents are generated from contracts/agent-model-capabilities.v2.json and
contracts/model-policy.v1.json, never edited by hand. Each generated block sits
between `<!-- BEGIN GENERATED: <name> -->` and `<!-- END GENERATED: <name> -->`.

  python3 scripts/render-model-routing-docs.py           # rewrite the blocks
  python3 scripts/render-model-routing-docs.py --check   # exit 1 on drift
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = 'contracts/agent-model-capabilities.v2.json'
POLICY = 'contracts/model-policy.v1.json'
TIERS = ('lightweight', 'standard', 'strong')
VENDORS = (('Anthropic', 'claude-code'), ('OpenAI (Codex)', 'codex-cli'), ('Google (Gemini)', 'gemini-cli'))
# v2 managed roles that still ship an agent definition. Retired three-loop and
# panel roles stay in the policy only for historical fixtures (ADR-0051).
ACTIVE_ROLES = (
    ('sdd-investigator', 'investigator', 'plugins/sdd-bootstrap/agents/investigator.md'),
    ('spec-reviewer-a/b', 'spec-reviewer-a', 'plugins/sdd-review-loop/agents/spec-reviewer-a.md'),
    ('sdd-evaluator', 'evaluator', 'plugins/sdd-quality-loop/agents/evaluator.md'),
    ('domain-reviewer-a/b', 'domain-reviewer-a', 'plugins/sdd-domain/agents/domain-reviewer-a.md'),
    ('wfi-auditor-a/b', 'workflow-auditor-a', 'plugins/sdd-quality-loop/agents/wfi-auditor-a.md'),
    ('diagnosis', 'diagnosis', None),
    ('self-improvement', 'self-improvement', None),
    ('implementer', 'implementer', None),
)
TARGETS = {
    'docs/agent-capability-matrix.md': ('model-tier-mapping', 'model-role-floors', 'model-historical'),
    'plugins/sdd-implementation/skills/implement-task/references/agent-delegation-policy.md': ('model-tier-summary',),
}
NOTE = ('Generated by `scripts/render-model-routing-docs.py` from `{reg}` and `{pol}`; '
        'do not edit by hand. Policy source date: {date}.')


def load(root):
    registry = json.loads((root / REGISTRY).read_text(encoding='utf-8'))
    policy = json.loads((root / POLICY).read_text(encoding='utf-8'))
    tiers = {m['name']: m for m in registry['models']}
    return registry, policy, tiers


def current(policy, tiers, tier, host):
    """Current policy models of one tier on one host, in policy order."""
    rows = []
    order = policy['roles']['investigator']['preferences']  # every current model, newest first per tier
    ranked = sorted(policy['models'], key=lambda m: order.index(m['id']) if m['id'] in order else len(order))
    for model in ranked:
        native = model['hosts'].get(host)
        if model['lifecycle'] == 'current' and native and tiers[model['id']]['canonical_tier'] == tier:
            rows.append('`{}` ({})'.format(native, tiers[model['id']]['default_effort']))
    return '、'.join(rows) or '現行モデルなし'


def frontmatter_model(root, rel):
    if rel is None:
        return '（エージェント定義なし）'
    match = re.search(r'(?m)^model:[ \t]*(\S+)[ \t]*$', (root / rel).read_text(encoding='utf-8'))
    return '`model: {}`'.format(match.group(1)) if match else '（model 指定なし）'


def blocks(root):
    registry, policy, tiers = load(root)
    note = NOTE.format(reg=REGISTRY, pol=POLICY, date=policy['source_date'][:10])
    mapping = ['| Tier | ' + ' | '.join(v for v, _ in VENDORS) + ' |', '|---|' + '---|' * len(VENDORS)]
    for tier in TIERS:
        mapping.append('| {} | {} |'.format(tier, ' | '.join(current(policy, tiers, tier, h) for _, h in VENDORS)))
    mapping += ['', 'Each cell lists the current (`lifecycle: current`) models of that tier as host-native IDs, with',
                'the registered default effort in parentheses. Automatic selection additionally requires per-role',
                'adoption evidence (`adoption`) in the policy. ' + note]
    floors = ['| Role | Agent definition | Minimum tier | Default effort |', '|---|---|---|---|']
    defaults = registry['role_defaults']
    for label, role, rel in ACTIVE_ROLES:
        capability = policy['roles'][role]['capability_role']
        profile = defaults.get(capability) if capability else None
        tier, effort = (profile['minimum_tier'], profile['default_effort']) if profile else ('—（継承）', '—')
        floors.append('| {} | {} | {} | {} |'.format(label, frontmatter_model(root, rel), tier, effort))
    floors += ['', 'Agents inherit the calling session\'s model; the minimum tier is enforced where the model is',
               'selected through the managed policy and reported when an inherited model is below it. ' + note]
    history = ['| Model | Lifecycle | Successor |', '|---|---|---|']
    successors = {}
    for model in policy['models']:
        for prior in model['successor_of']:
            successors.setdefault(prior, []).append(model['id'])
    for model in policy['models']:
        if model['lifecycle'] != 'current':
            history.append('| `{}` | {} | {} |'.format(model['id'], model['lifecycle'],
                                                        '、'.join('`{}`'.format(x) for x in successors.get(model['id'], [])) or '—'))
    history += ['', '`candidate` entries are version-less aliases kept for explicit pins; `historical` entries stay',
                'registered for compatibility and are never selected automatically. ' + note]
    summary = []
    for tier in TIERS:
        summary.append('- `{}`: {}'.format(tier, '; '.join('{} {}'.format(v, current(policy, tiers, tier, h)) for v, h in VENDORS)))
    summary += ['', 'Role floors (registry `role_defaults`): ' + ', '.join(
        '{} {} / {}'.format(label, *((defaults[policy['roles'][role]['capability_role']]['minimum_tier'],
                                       defaults[policy['roles'][role]['capability_role']]['default_effort'])
                                      if policy['roles'][role]['capability_role'] else ('inherit', 'session')))
        for label, role, _ in ACTIVE_ROLES[:3]) + '. ' + note]
    return {'model-tier-mapping': mapping, 'model-role-floors': floors, 'model-historical': history,
            'model-tier-summary': summary}


def render(text, name, body):
    pattern = re.compile(r'(<!-- BEGIN GENERATED: {0} -->\n).*?(<!-- END GENERATED: {0} -->)'.format(re.escape(name)), re.S)
    if len(pattern.findall(text)) != 1:
        raise SystemExit('render-model-routing-docs: expected exactly one generated block "{}"'.format(name))
    return pattern.sub(lambda m: m.group(1) + '\n'.join(body) + '\n' + m.group(2), text)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--check', action='store_true', help='exit 1 when a generated block is stale')
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args(argv)
    generated = blocks(args.root)
    stale = []
    for rel, names in TARGETS.items():
        path = args.root / rel
        before = path.read_text(encoding='utf-8')
        after = before
        for name in names:
            after = render(after, name, generated[name])
        if after != before:
            stale.append(rel)
            if not args.check:
                path.write_text(after, encoding='utf-8')
    if args.check and stale:
        print('render-model-routing-docs: stale generated tables in: ' + ', '.join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
